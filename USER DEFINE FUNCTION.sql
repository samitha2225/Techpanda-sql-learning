CREATE DATABASE USER_DEFINE;
USE USER_DEFINE;

DELIMITER //

CREATE FUNCTION ADD_NUM (NUM1 INT,NUM2 INT)
RETURNS INT
DETERMINISTIC
BEGIN
RETURN NUM1+NUM2;
END //

DELIMITER ;

SELECT ADD_NUM(100,100);


DELIMITER //

CREATE FUNCTION SUB_NUM(NUM1 INT,NUM2 INT)
RETURNS INT
DETERMINISTIC
BEGIN
RETURN NUM1-NUM2;
END //
DELIMITER ;

SELECT SUB_NUM(200,100);

DELIMITER //
CREATE FUNCTION SQUARE_NUM(N INT)
RETURNS INT
DETERMINISTIC
BEGIN
RETURN N*N;
END //
DELIMITER ;

SELECT SQUARE_NUM(6);

DELIMITER //
CREATE FUNCTION CUBE_NUM(N INT)
RETURNS INT
DETERMINISTIC
BEGIN
RETURN N*N*N;
END //
 DELIMITER ;
 
 SELECT CUBE_NUM (3);
 
DELIMITER //
CREATE FUNCTION GREATER_OF_NUM(NUM1 INT, NUM2 INT)
RETURNS VARCHAR(20)
DETERMINISTIC
BEGIN
IF NUM1 > NUM2 THEN 
RETURN 'GREATER';
ELSE 
RETURN 'SMALLER';
END IF;
END //
DELIMITER ;
SELECT GREATER_OF_NUM(67, 88);

